/**
 * 分类选择里「其他…」那一项 —— 本地上传和百炼同步两块界面共用同一套规则。
 *
 * **它是一个纯界面的哨兵值，永远不会发给后端**：选中它时发出去的是用户填的那段文字。
 * 用 `__other__` 而不是「其他」两个字，是为了不和真叫「其他」的分类撞上——
 * 分类名是用户随便填的，包括「其他」。真撞上时，选项标签是「其他」，
 * 哨兵那一项是「其他…」（带省略号），仍是两行、分得清。
 *
 * **为什么要单独一个模块**：两块界面都要「选其他 + 手填类型名」。哨兵值两边各写一份的话，
 * 漂移的表现是「有一边选了其他，却把 `__other__` 当成类型名发了出去」——
 * 后端会把它当合法分类收下（它就是一段普通文本），于是库里多出一个叫 `__other__` 的分类，
 * 而且什么都不报。取值规则同理，所以都只放这一份。
 */

/** 哨兵值。只用于界面，绝不作为分类值发给后端。 */
export const OTHER = '__other__'

/**
 * 自定义类型名的长度上限。
 *
 * **必须和后端的规则一致**：那边是 {@code PgVectorSql} 的
 * `[\p{L}\p{N} _\-.]{1,20}`，超了或用了别的字符直接 400
 * （`error.kb.classificationInvalid`）。这里只是提前拦一道，让用户不用等一次往返。
 */
export const MAX_CUSTOM_LENGTH = 20

/**
 * 这一次实际要用的分类值。
 *
 * @param {string} choice 下拉框的模型值，可能是 {@link OTHER}
 * @param {string} custom 手填的类型名，只在 choice 是 {@link OTHER} 时有意义
 * @returns {string} 分类值；空串表示还没选好，调用方应据此拦下提交（后端对空分类直接 400）
 */
export function resolveCategory(choice, custom) {
  return choice === OTHER ? (custom || '').trim() : choice || ''
}
