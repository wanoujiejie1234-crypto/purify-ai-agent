package com.purify.purifyaiagent.agent.loop;

/**
 * 循环的判据种类——也就是「卡住」有哪几种长相。
 *
 * <p>分开列出来是为了让检测器和处置器各自按类型判断，而不是所有情况共用一个布尔值：
 * 处置策略往往要看是哪一种循环（比如「同一个调用重复 N 次」和「A/B 来回横跳」，
 * 该问用户的问题是不一样的），日志里也需要一眼看出命中的是哪一条判据。
 */
public enum LoopType {

    /** 连续多步调用同一组工具、且参数完全相同。最常见的一种，等价于 OpenManus 的 is_stuck 判据。 */
    REPEATED_TOOL_CALL,

    /**
     * 两步一循环：A、B、A、B……。
     *
     * <p>单看「连续两次是否相同」是发现不了它的——每一步和上一步都不一样，
     * 但整个序列在原地打转。所以它需要单独一条判据。
     */
    ALTERNATING_TOOL_CALL,

    /** 连续多步模型说的话一模一样。常见于「工具换了，说法没换，其实一点进展都没有」。 */
    REPEATED_ANSWER
}
